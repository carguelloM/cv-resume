#!/usr/bin/env python3
"""
Generate the LaTeX publication lists from pubs/*.bib.\

This script was generated by Claude Code and edited by me. 

  makepubs.py cv      -> Publications and Patents sections for cv.tex
  makepubs.py resume  -> \\item list for resume.tex (no patents)
  makepubs.py check   -> only report problems; exit 1 if there are any

Output goes to stdout; problems are reported on stderr.
"""

import sys
import bibcv

# cv.tex environments (from resume.cls) for numbered subsections
CV_ENV = {
    "conference": "rSubsection_Conference",
    "journal": "rSubsection_Journal",
    "poster": "rSubsection_Poster",
    "artifact": "rSubsection_Artifact",
}
# label prefixes used by those environments (CP1, JA1, ...), for 'related'
CV_LABEL = {"conference": "CP", "journal": "JA", "poster": "P", "artifact": "A",
            "patent": "PT"}
CV_PLAIN_LIST = r"\begin{itemize}[leftmargin=2em, label=$\cdot$, " \
    r"topsep=0pt, itemsep=0.2em, parsep=0pt]"


def cv_labels(groups):
    """Citekey -> CV label, numbered in the same order as resume.cls."""
    labels = {}
    for key, prefix in CV_LABEL.items():
        for i, e in enumerate(groups[key], 1):
            labels[e.key] = f"{prefix}{i}"
    return labels


def cv(groups, out):
    out.append("% generated by bin/makepubs.py from pubs/*.bib -- do not edit")
    labels = cv_labels(groups)
    pubs = [k for k, _ in bibcv.SECTIONS if k != "patent" and groups[k]]
    if pubs:
        out.append(r"\begin{rSection}{Publications}")
        for key, heading in bibcv.SECTIONS:
            if key == "patent" or not groups[key]:
                continue
            env = CV_ENV.get(key)
            if env:
                out.append(f"  \\begin{{{env}}}{{{heading}}}")
            else:
                out.append(f"  {{\\rolefont {heading}}}")
                out.append("  " + CV_PLAIN_LIST)
            for e in groups[key]:
                out.append(f"    \\item \\hypertarget{{{e.key}}}{{}}"
                           f"{bibcv.format_entry(e, labels)}  % {e.key}")
            out.append(f"  \\end{{{env}}}" if env else r"  \end{itemize}")
            out.append("")
        out.append(r"\end{rSection}")
    if groups["patent"]:
        out.append("")
        out.append(r"\begin{rSection}{Patents}")
        out.append(r"  \begin{rSubsection_Patent}")
        for e in groups["patent"]:
            out.append(f"    \\item \\hypertarget{{{e.key}}}{{}}"
                       f"{bibcv.format_entry(e, labels)}  % {e.key}")
        out.append(r"  \end{rSubsection_Patent}")
        out.append(r"\end{rSection}")


def resume(groups, out):
    out.append("% generated by bin/makepubs.py from pubs/*.bib -- do not edit")
    entries = [e for k, _ in bibcv.SECTIONS
               if k not in ("patent", "artifact")
               for e in groups[k]]
    entries.sort(key=lambda e: e.sortkey(), reverse=True)
    for e in entries:
        out.append(f"\\item {bibcv.format_entry(e)}  % {e.key}")



if len(sys.argv) != 2 or sys.argv[1] not in ("cv", "resume", "check"):
    print(__doc__, file=sys.stderr)
    sys.exit(1)
entries = bibcv.load(bibcv.PUBS_DIR)
errors = 0
for e in entries:
    for p in bibcv.check(e):
        print(f"{e.path}: {p}", file=sys.stderr)
        errors += 1
groups = bibcv.by_section(entries)
labels = cv_labels(groups)
for e, p in bibcv.check_related(entries):
    print(f"{e.path}: {p}", file=sys.stderr)
    errors += 1
for e in entries:
    for k in bibcv.related_keys(e):
        if k in {x.key for x in entries} and k not in labels:
            print(f"{e.path}: related entry '{k}' has no CV label "
                  "(only " + ", ".join(CV_LABEL) + " do)",
                  file=sys.stderr)
            errors += 1
if sys.argv[1] == "check":
    print(f"{len(entries)} entries, {errors} problems")
    sys.exit(1 if errors else 0)
out = []
(cv if sys.argv[1] == "cv" else resume)(groups, out)
print("\n".join(out))
sys.exit(0) 

