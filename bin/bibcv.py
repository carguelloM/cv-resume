#!/usr/bin/env python3
"""
Shared library: parse the .bib files in pubs/ and format them as LaTeX.
This script was generated by Claude Code and edited by me. 
Inspiration from David Kotz vita

  * one entry per file, named after its citekey ('lastname:short' ->
    'lastname-short.bib')
  * text fields hold Unicode, not LaTeX ('–' en-dash, '“ ”' quotes, ⦉emph⦊)
  * 'category' decides where an entry is listed (see CATEGORY_SECTION)
  * month / publisher may be bare @string names (may, ieee, ...)
"""

import os
import re
import sys

ME = "Cesar Arguello"
PUBS_DIR = "pubs"

MONTHS = {m: n for n, m in enumerate( "jan feb mar apr may jun jul aug sep oct nov dec".split(), 1)}
MONTH_NAMES = ["", "January", "February", "March", "April", "May", "June",
               "July", "August", "September", "October", "November",
               "December"]

# Bare @string names we know how to expand.
STRINGS = {"ieee": "IEEE", "acm": "ACM", "usenix": "USENIX Association", "springer": "Springer"}

STRINGS.update({m: MONTH_NAMES[n] for m, n in MONTHS.items()})

# CV sections, in the order they appear.
SECTIONS = [
    ("conference", "Refereed Conference Papers"),
    ("journal", "Refereed Journal Articles"),
    ("chapter", "Book Chapters"),
    ("poster", "Posters"),
    ("techreport", "Technical Reports"),
    ("patent", "Patents"),
    ("artifact", "Artifacts"),
]
# category -> CV section; None means kept in pubs/ but not listed.
CATEGORY_SECTION = {
    "conference": "conference",
    "journal": "journal",
    "chapter": "chapter",
    "poster": "poster",
    "techreport": "techreport",
    "patent": "patent",               # issued
    "patent-application": "patent",   # filed / pending
    "artifact": "artifact",
    "draft": None,
}

# The only fields allowed in pubs/ (makepubs.py check flags anything else).
# volume, number, pages, publisher are kept for completeness but not printed.
VALID_FIELDS = ["author", "title", "booktitle", "journal", "howpublished",
               "institution", "year", "month", "day", "volume", "number",
               "pages", "publisher", "doi", "url",
               "category", "acceptpercent", "note", "related"]

REQUIRED = {
    "inproceedings": ["author", "title", "booktitle", "year", "category"],
    "article": ["author", "title", "journal", "year", "category"],
    "misc": ["author", "title", "year", "category"],
    "techreport": ["author", "title", "institution", "year", "category"],
    "incollection": ["author", "title", "booktitle", "year", "category"],
}


class Entry:
    def __init__(self, path, etype, key, fields, raw_fields):
        self.path = path                # path of bib entry
        self.etype = etype              # type of pub (e.g., InProceedings, Misc, etc)
        self.type = etype.lower()
        self.key = key                  # bib tex key
        self.fields = fields          # all .bib fields after "cleaning"
        self.raw = raw_fields         # all .bib fields raw
    
    def get(self, name, default=""):
        return self.fields.get(name, default)

    @property
    def section(self):
        return CATEGORY_SECTION.get(self.get("category"))

    def sortkey(self):
        month = self.get("month").lower()[:3]
        return (int(self.get("year") or 0), MONTHS.get(month, 0),
                int(self.get("day") or 0) if self.get("day").isdigit() else 0)


######################### Parser #################################

def read_braced(s, i):
    """s[i] == '{'; return (content, index after matching '}')."""
    depth, start = 0, i
    while i < len(s):
        c = s[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return s[start + 1:i], i + 1
        i += 1
    raise ValueError("unbalanced braces")


def clean(value, bare):
    if bare:
        return STRINGS.get(value.lower(), value)
    # strip protective inner braces like {{Title}} or {IoT}
    return re.sub(r"\s+", " ", value.replace("{", "").replace("}", "")).strip()



ENTRY_START = re.compile(r"^@(?!comment\b)\w+\s*\{", re.M | re.I)
# Lines starting with '%' are comments, even inside an entry
COMMENT_LINE = re.compile(r"^[ \t]*%.*\n?", re.M)


def parse_file(path):
    with open(path, encoding="utf-8") as f:
        text = COMMENT_LINE.sub("", f.read()) ## delete comments 
    start = ENTRY_START.search(text)
    if not start:
        raise ValueError(f"{path}: no bibtex entry")
    at = start.start()
    m = re.match(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", text[at:])
    if not m:
        raise ValueError(f"{path}: cannot parse entry header")
    etype, key = m.group(1), m.group(2)
    i = at + m.end()
    fields, raw = {}, {}
    fm = re.compile(r"\s*([A-Za-z][\w-]*)\s*=\s*")
    while True:
        while i < len(text) and text[i] in " \t\r\n,":
            i += 1
        if i >= len(text) or text[i] == "}":
            break
        m = fm.match(text, i)
        if not m:
            raise ValueError(f"{path}: cannot parse field near: "
                             f"{text[i:i + 40]!r}")
        name = m.group(1).lower()
        i = m.end()
        if text[i] == "{":
            value, i = read_braced(text, i)
            bare = False
        elif text[i] == '"':
            j = text.index('"', i + 1)
            value, i, bare = text[i + 1:j], j + 1, False
        else:
            m = re.match(r"[^,}\s]+", text[i:])
            value, i, bare = m.group(0), i + m.end(), True
        raw[name] = (value, bare)
        fields[name] = clean(value, bare)
    return Entry(path, etype, key, fields, raw)


def load(*dirs):
    entries = []
    for d in dirs:
        if not os.path.isdir(d):
            continue
        for fn in sorted(os.listdir(d)):
            if fn.endswith(".bib"):
                entries.append(parse_file(os.path.join(d, fn)))
    return entries


######################### Checker #################################

def check(e):
    """Return a list of problems with entry e (strings)."""
    problems = []

    for name in REQUIRED.get(e.type, ["author", "title", "year", "category"]):
        if not e.get(name):
            problems.append(f"missing field '{name}'")
    if e.section == "patent" and not e.get("howpublished"):
        problems.append("missing field 'howpublished' (patent number)")

    ## entry file should match file name 
    expect_file = e.key.replace(":", "-") + ".bib"
    if os.path.basename(e.path) != expect_file:
        problems.append(f"filename should be {expect_file}")

    for name, (value, bare) in e.raw.items():
        if "\\" in value:
            problems.append(f"'{name}' contains a backslash (use Unicode)")
        if "FIXME" in name.upper():
            problems.append(f"FIXME: {value}")

    if re.search(r"\d-{1,2}\d", e.get("pages")):
        problems.append("pages should use an en-dash '–'")

    for name in e.raw:
        if name not in VALID_FIELDS:
            problems.append(f"invalid field '{name}'")
    
    cat = e.get("category")
    if cat and cat not in CATEGORY_SECTION:
        problems.append(f"unknown category '{cat}' (use one of: "
                        + ", ".join(CATEGORY_SECTION) + ")")
        
    if "accepted" in e.get("note").lower() and e.get("doi"):
        problems.append("has a DOI but note still says 'Accepted'")
    return problems


####################### LaTeX ####################################

#### Unicode to LaTex mapping
TEX = [
    ("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
    ("#", r"\#"), ("_", r"\_"), ("~", r"\textasciitilde{}"),
    ("–", "--"), ("—", "---"), ("“", "``"), ("”", "''"),
    ("‘", "`"), ("’", "'"), ("…", r"\ldots{}"), ("⦉", r"\emph{"),
    ("⦊", "}"), ("¶", r"\par "), ("⁋", r"\par "), (" ", "~"),
]


def tex(s):
    for a, b in TEX:
        s = s.replace(a, b)
    return s

### Boldface name 
def format_authors(e):
    names = [n.strip() for n in e.get("author").split(" and ") if n.strip()]
    names = [n if n.lower() != "others" else "et al." for n in names]
    out = [r"\textbf{" + tex(n) + "}" if n == ME else tex(n) for n in names]
    if len(out) <= 2:
        return " and ".join(out)
    return ", ".join(out[:-1]) + ", and " + out[-1]


def format_title(e):
    title = tex(e.get("title")).rstrip(".")
    link = ""
    if e.get("doi"):
        link = "https://doi.org/" + e.get("doi")
    elif e.get("url"):
        link = e.get("url")
    if link:
        title = r"\href{" + link.replace("%", r"\%").replace("#", r"\#") \
            + "}{" + title + "}"
    return title


def format_date(e):
    month = e.get("month")
    parts = [month] if month else []
    if e.get("day"):
        parts.append(e.get("day") + ",")
    parts.append(e.get("year"))
    return " ".join(parts)


def related_keys(e):
    """Citekeys named in e's 'related' field (comma-separated)."""
    return [k.strip() for k in e.get("related").split(",") if k.strip()]


def check_related(entries):
    """Return (entry, problem) pairs for bad 'related' fields."""
    keys = {e.key for e in entries}
    problems = []
    for e in entries:
        # conference papers are what others relate to, never the other way
        if e.section == "conference" and related_keys(e):
            problems.append((e, "conference papers cannot have 'related'"))
        for k in related_keys(e):
            if k == e.key:
                problems.append((e, "related to itself"))
            elif k not in keys:
                problems.append((e, f"related entry '{k}' does not exist"))
    return problems


def format_entry(e, labels=None):
    """One publication as a LaTeX sentence (no \\item).

    labels maps citekeys to CV labels like 'CP1'; when given, the 'related'
    field prints as 'Related to CP1' linked to that entry. Without it (the
    resume), 'related' is left out.
    """
    s = [format_authors(e) + ".", format_title(e) + "."]
    sec = e.section
    if sec == "patent":
        s.append(tex(e.get("howpublished")) + ".")
        verb = "Issued" if e.get("category") == "patent" else "Filed"
        s.append(f"{verb} {format_date(e)}.")
        if e.get("category") == "patent-application":
            s.append(r"\textit{(Pending.)}")
    else:
        venue = e.get("booktitle") or e.get("journal") \
            or e.get("howpublished") or e.get("institution")
        if venue:
            s.append(r"\textit{" + tex(venue) + "},")
        s.append(e.get("year") + ".")
        if e.get("acceptpercent") and sec in ("conference", "journal"):
            s.append(f"Acceptance rate {e.get('acceptpercent')}\\%.")
    note = e.get("note") if sec != "patent" else ""
    if note:
        s.append(tex(note).rstrip(".") + ".")
    refs = [rf"\hyperlink{{{k}}}{{{labels[k]}}}"
            for k in related_keys(e) if labels and k in labels]
    if refs:
        s.append("Related to " + ", ".join(refs) + ".")
    return " ".join(s)


def by_section(entries):
    groups = {k: [] for k, _ in SECTIONS}
    for e in entries:
        if e.section in groups:
            groups[e.section].append(e)
    for k in groups:
        groups[k].sort(key=lambda e: e.sortkey(), reverse=True)
    return groups


if __name__ == "__main__":
    for p in sys.argv[1:]:
        print(format_entry(parse_file(p)))
